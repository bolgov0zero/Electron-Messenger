'use strict';
// Режим обслуживания: пока включён, запись в базу запрещена. Нужен на время переноса
// на другой движок — всё, что записалось бы после снимка, потерялось бы.
// Запросы на чтение работают; изменяющие запросы клиентов получают 503, а любая
// попытка записи из кода (фоновые задачи, федерация) отклоняется на уровне dal.
let reason = null;
let since = 0;
module.exports = {
  on(why) { reason = why || 'maintenance'; since = Date.now(); },
  off() { reason = null; },
  isOn: () => reason !== null,
  info: () => (reason === null ? null : { reason, since }),
};
