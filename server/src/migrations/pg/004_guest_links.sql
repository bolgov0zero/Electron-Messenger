-- Гостевые ссылки: вход в группу или комнату без учётной записи, на ограниченное время (см. guest.js).
-- В базе только хеш токена. Одна ссылка — один гость, привязанный к устройству первого входа.
CREATE TABLE IF NOT EXISTS guest_links (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id       BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    token_hash    TEXT NOT NULL UNIQUE,
    created_by    BIGINT,
    created_at    BIGINT NOT NULL DEFAULT (extract(epoch from now())::bigint),
    expires_at    BIGINT NOT NULL,
    revoked_at    BIGINT,
    ended_at      BIGINT,
    guest_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL DEFERRABLE INITIALLY IMMEDIATE,
    guest_name    TEXT,
    device_hash   TEXT,
    base_msg_id   BIGINT NOT NULL DEFAULT 0,
    first_used_at BIGINT,
    last_used_at  BIGINT
  );
CREATE INDEX IF NOT EXISTS idx_guest_links_chat ON guest_links(chat_id);
CREATE INDEX IF NOT EXISTS idx_guest_links_user ON guest_links(guest_user_id);
