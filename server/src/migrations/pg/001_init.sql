-- Названия пространств различаются без учёта регистра (в SQLite было COLLATE NOCASE)
CREATE UNIQUE INDEX IF NOT EXISTS uq_workspaces_name_ci ON workspaces (lower(name));

-- Полнотекстовый поиск: русская морфология. Шифротексты секретных чатов (iv не пуст) в индекс не попадают.
ALTER TABLE messages ADD COLUMN IF NOT EXISTS tsv tsvector
  GENERATED ALWAYS AS (to_tsvector('russian', CASE WHEN iv IS NULL THEN text ELSE '' END)) STORED;
CREATE INDEX IF NOT EXISTS idx_messages_tsv ON messages USING GIN (tsv);
