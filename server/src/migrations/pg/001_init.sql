-- Схема PostgreSQL, версия 1. Получена из схемы SQLite (db.js) и далее правится только новыми нумерованными миграциями.

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT NOT NULL,
    display_name TEXT NOT NULL,
    is_admin BIGINT DEFAULT 0,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  , tag TEXT DEFAULT NULL, last_seen_at BIGINT, is_bot BIGINT DEFAULT 0, banned BIGINT DEFAULT 0, must_change_password BIGINT DEFAULT 0, sessions_valid_from BIGINT, totp_secret TEXT, totp_pending_secret TEXT, totp_required BIGINT DEFAULT 0, can_announce BIGINT DEFAULT 0, workspace_id BIGINT NOT NULL DEFAULT 1, fed_instance TEXT, fed_login TEXT, fed_avatar_v TEXT);

CREATE TABLE IF NOT EXISTS chats (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type TEXT NOT NULL CHECK(type IN ('direct', 'group', 'room')),
    name TEXT,
    created_by BIGINT REFERENCES users(id),
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  , parent_id BIGINT REFERENCES chats(id) ON DELETE CASCADE, position BIGINT DEFAULT 0, topics_manual BIGINT DEFAULT 0, is_secret BIGINT DEFAULT 0, read_only BIGINT DEFAULT 0, fed_instance TEXT, fed_chat_id BIGINT, fed_avatar_v TEXT);

CREATE TABLE IF NOT EXISTS chat_members (
    chat_id BIGINT REFERENCES chats(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    joined_at BIGINT DEFAULT (extract(epoch from now())::bigint), hidden_at BIGINT, pinned_at BIGINT,
    PRIMARY KEY (chat_id, user_id)
  );

CREATE TABLE IF NOT EXISTS messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT REFERENCES chats(id) ON DELETE CASCADE,
    sender_id BIGINT REFERENCES users(id),
    text TEXT NOT NULL,
    edited_at BIGINT,
    deleted BIGINT DEFAULT 0,
    sent_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  , reply_to_id BIGINT REFERENCES messages(id), attachment TEXT, mentions TEXT, forward_data TEXT, link_preview TEXT, system_kind TEXT, iv TEXT, fed_uid TEXT, fed_seq BIGINT);

CREATE TABLE IF NOT EXISTS message_status (
    message_id BIGINT REFERENCES messages(id) ON DELETE CASCADE,
    user_id BIGINT REFERENCES users(id) ON DELETE CASCADE,
    delivered_at BIGINT,
    read_at BIGINT,
    PRIMARY KEY (message_id, user_id)
  );

CREATE TABLE IF NOT EXISTS reactions (
    message_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    reaction TEXT NOT NULL,
    PRIMARY KEY (message_id, user_id, reaction),
    FOREIGN KEY (message_id) REFERENCES messages(id) ON DELETE CASCADE,
    FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
  );

CREATE TABLE IF NOT EXISTS settings (
    key TEXT PRIMARY KEY,
    value TEXT NOT NULL
  );

CREATE TABLE IF NOT EXISTS chat_read_state (
    user_id      BIGINT NOT NULL,
    chat_id      BIGINT NOT NULL,
    last_read_id BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (user_id, chat_id)
  );

CREATE TABLE IF NOT EXISTS push_subscriptions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    endpoint TEXT UNIQUE NOT NULL,
    keys TEXT NOT NULL,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  , app_url TEXT);

CREATE TABLE IF NOT EXISTS webhooks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token TEXT UNIQUE NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id),
    chat_id BIGINT NOT NULL REFERENCES chats(id),
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  );

CREATE TABLE IF NOT EXISTS muted_chats (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    chat_id BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE, until BIGINT,
    PRIMARY KEY (user_id, chat_id)
  );

CREATE TABLE IF NOT EXISTS pinned_messages (
    chat_id    BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
    message_id BIGINT NOT NULL REFERENCES messages(id) ON DELETE CASCADE,
    pinned_by  BIGINT REFERENCES users(id) ON DELETE SET NULL,
    pinned_at  BIGINT DEFAULT (extract(epoch from now())::bigint),
    PRIMARY KEY (chat_id, message_id)
  );

CREATE TABLE IF NOT EXISTS announcements (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind         TEXT NOT NULL,
    text         TEXT NOT NULL,
    author_id    BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at   BIGINT NOT NULL DEFAULT (extract(epoch from now())::bigint),
    start_at     BIGINT NOT NULL,
    sent_at      BIGINT,
    duration_min BIGINT,
    expires_at   BIGINT,
    target       TEXT NOT NULL DEFAULT 'all',
    targets      TEXT
  );

CREATE TABLE IF NOT EXISTS announcement_dismissed (
    announcement_id BIGINT NOT NULL REFERENCES announcements(id) ON DELETE CASCADE,
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    dismissed_at    BIGINT NOT NULL DEFAULT (extract(epoch from now())::bigint),
    PRIMARY KEY (announcement_id, user_id)
  );

CREATE TABLE IF NOT EXISTS chat_folders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    color TEXT NOT NULL DEFAULT '#4ea4ff',
    icon TEXT NOT NULL DEFAULT 'folder',
    position BIGINT NOT NULL DEFAULT 0
  );

CREATE TABLE IF NOT EXISTS chat_folder_items (
    folder_id BIGINT NOT NULL REFERENCES chat_folders(id) ON DELETE CASCADE,
    chat_id BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
    PRIMARY KEY (folder_id, chat_id)
  );

CREATE TABLE IF NOT EXISTS admin_audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT REFERENCES users(id),
    category TEXT NOT NULL,
    action TEXT NOT NULL,
    target TEXT,
    ip TEXT,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  );

CREATE TABLE IF NOT EXISTS secret_chat_devices (
    chat_id BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_id TEXT NOT NULL,
    device_label TEXT,
    platform TEXT NOT NULL DEFAULT 'electron',
    approved_at BIGINT DEFAULT (extract(epoch from now())::bigint),
    PRIMARY KEY (chat_id, user_id, device_id)
  );

CREATE TABLE IF NOT EXISTS secret_key_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
    requester_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    requester_device_id TEXT NOT NULL,
    requester_device_label TEXT,
    requester_platform TEXT NOT NULL DEFAULT 'electron',
    ephemeral_pubkey TEXT NOT NULL,
    code_hash TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','approved')),
    wrapped_secret TEXT,
    approver_ephemeral_pubkey TEXT,
    approver_user_id BIGINT REFERENCES users(id),
    expires_at BIGINT NOT NULL,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  , requester_ip TEXT);

CREATE TABLE IF NOT EXISTS secret_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    chat_id BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
    granter_user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    granter_device_id TEXT NOT NULL,
    code_hash TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','redeemed')),
    request_id BIGINT,
    expires_at BIGINT NOT NULL,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  );

CREATE TABLE IF NOT EXISTS modules (
    key TEXT PRIMARY KEY,
    enabled BIGINT NOT NULL DEFAULT 0,
    updated_at BIGINT,
    updated_by BIGINT REFERENCES users(id) ON DELETE SET NULL
  );

CREATE TABLE IF NOT EXISTS module_devices (
    module TEXT NOT NULL,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_id TEXT NOT NULL,
    client TEXT,
    version TEXT,
    enabled BIGINT NOT NULL DEFAULT 0,
    updated_at BIGINT DEFAULT (extract(epoch from now())::bigint), pack_version TEXT,
    PRIMARY KEY (module, user_id, device_id)
  );

CREATE TABLE IF NOT EXISTS module_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module TEXT NOT NULL,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    device_id TEXT,
    client TEXT,
    version TEXT,
    event TEXT NOT NULL,
    detail TEXT,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  );

CREATE TABLE IF NOT EXISTS workspaces (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  , fed_uid TEXT, fed_host TEXT);

CREATE TABLE IF NOT EXISTS contacts (
    owner_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    contact_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint),
    PRIMARY KEY (owner_id, contact_id)
  );

CREATE TABLE IF NOT EXISTS user_blocks (
    blocker_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    blocked_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint),
    PRIMARY KEY (blocker_id, blocked_id)
  );

CREATE TABLE IF NOT EXISTS dm_limits (
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    recipient_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    n BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (sender_id, recipient_id)
  );

CREATE TABLE IF NOT EXISTS user_workspaces (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    PRIMARY KEY (user_id, workspace_id)
  );

CREATE TABLE IF NOT EXISTS fed_peers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id TEXT NOT NULL UNIQUE,
    name TEXT NOT NULL,
    url TEXT,
    pub TEXT NOT NULL,
    role TEXT NOT NULL CHECK(role IN ('in','out')),
    status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','paused')),
    last_in_seq BIGINT NOT NULL DEFAULT 0,
    last_contact_at BIGINT,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  , proto BIGINT NOT NULL DEFAULT 0, ver TEXT, virt BIGINT NOT NULL DEFAULT 0, sp BIGINT NOT NULL DEFAULT 0);

CREATE TABLE IF NOT EXISTS fed_invites (
    token_hash TEXT PRIMARY KEY,
    expires_at BIGINT NOT NULL,
    used_at BIGINT,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  , secret TEXT);

CREATE TABLE IF NOT EXISTS fed_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    peer_id BIGINT NOT NULL REFERENCES fed_peers(id) ON DELETE CASCADE,
    ev TEXT NOT NULL,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  );

CREATE TABLE IF NOT EXISTS fed_stats (
    bucket BIGINT NOT NULL,
    peer_id BIGINT NOT NULL,
    bytes_out BIGINT NOT NULL DEFAULT 0,
    bytes_in BIGINT NOT NULL DEFAULT 0,
    rej_limit BIGINT NOT NULL DEFAULT 0,
    rej_rate BIGINT NOT NULL DEFAULT 0,
    rej_blocked BIGINT NOT NULL DEFAULT 0,
    rej_other BIGINT NOT NULL DEFAULT 0,
    reconnects BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (bucket, peer_id)
  );

CREATE TABLE IF NOT EXISTS push_prefs (
  user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
  show_text BIGINT NOT NULL DEFAULT 1,
  quiet_from BIGINT,
  quiet_to BIGINT,
  tz TEXT
);

CREATE TABLE IF NOT EXISTS chat_invites (
    chat_id BIGINT NOT NULL REFERENCES chats(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    invited_by BIGINT,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint),
    PRIMARY KEY (chat_id, user_id)
  );

CREATE TABLE IF NOT EXISTS fed_space_servers (
    space_uid TEXT NOT NULL,
    instance_id TEXT NOT NULL,
    name TEXT NOT NULL,
    pub TEXT NOT NULL,
    parent TEXT NOT NULL DEFAULT '',
    state TEXT NOT NULL DEFAULT 'active',
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint),
    PRIMARY KEY (space_uid, instance_id)
  );

CREATE TABLE IF NOT EXISTS fed_space_offers (
    space_uid TEXT PRIMARY KEY,
    host TEXT NOT NULL,
    name TEXT NOT NULL,
    from_inst TEXT NOT NULL,
    tree TEXT NOT NULL,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  );

CREATE TABLE IF NOT EXISTS fed_space_asks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_uid TEXT NOT NULL,
    proposer TEXT NOT NULL,
    target TEXT NOT NULL,
    target_name TEXT NOT NULL,
    target_pub TEXT NOT NULL,
    approved BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  );

CREATE TABLE IF NOT EXISTS fed_key_checks (
    instance_id TEXT PRIMARY KEY,
    pub TEXT NOT NULL,
    created_at BIGINT DEFAULT (extract(epoch from now())::bigint)
  );

CREATE TABLE IF NOT EXISTS metrics_5m (
  t        BIGINT PRIMARY KEY,   
  n        BIGINT NOT NULL,      
  cpu_sum  DOUBLE PRECISION NOT NULL,
  lag_max  DOUBLE PRECISION NOT NULL,
  on_sum   DOUBLE PRECISION NOT NULL,
  on_n     BIGINT NOT NULL
);

