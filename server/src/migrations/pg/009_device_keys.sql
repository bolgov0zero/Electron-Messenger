-- Ключи устройств: вход без пароля, когда токен не принят (см. devices.js).
-- kind = 'device' — ключ пары «человек + устройство», 'profile' — ключ профиля на сетевом диске (режим «Высокая доступность»).
-- В базе только хеш ключа; revoked_at — отозван администратором (у профиля это запрет регистрации новых устройств).
CREATE TABLE IF NOT EXISTS device_keys (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    kind         TEXT NOT NULL,
    device_id    TEXT,
    platform     TEXT NOT NULL DEFAULT 'app',
    name         TEXT NOT NULL DEFAULT '',
    os_user      TEXT NOT NULL DEFAULT '',
    key_hash     TEXT NOT NULL UNIQUE,
    prev_hash    TEXT,
    prev_at      BIGINT,
    parent_id    BIGINT,
    created_at   BIGINT NOT NULL DEFAULT (extract(epoch from now())::bigint),
    last_used_at BIGINT,
    revoked_at   BIGINT
);
CREATE INDEX IF NOT EXISTS idx_device_keys_user ON device_keys(user_id);
