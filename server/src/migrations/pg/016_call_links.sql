-- Ссылки на видеозвонок для гостей (см. calllinks.js): многоразовая ссылка, гость без учётной записи привязан к устройству.
-- can_call_links — право создавать такие ссылки (включает админ сервера; у админа есть всегда).
ALTER TABLE users ADD COLUMN IF NOT EXISTS can_call_links BIGINT DEFAULT 0;
CREATE TABLE IF NOT EXISTS call_links (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token      TEXT NOT NULL UNIQUE,
    room       TEXT NOT NULL,
    created_by BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    created_at BIGINT NOT NULL DEFAULT (extract(epoch from now())::bigint),
    expires_at BIGINT NOT NULL,
    closed_at  BIGINT
  );
CREATE INDEX IF NOT EXISTS idx_call_links_owner ON call_links(created_by);
CREATE TABLE IF NOT EXISTS call_link_guests (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    link_id     BIGINT NOT NULL REFERENCES call_links(id) ON DELETE CASCADE DEFERRABLE INITIALLY IMMEDIATE,
    name        TEXT NOT NULL,
    device_hash TEXT NOT NULL,
    status      TEXT NOT NULL DEFAULT 'wait',
    asked_at    BIGINT NOT NULL DEFAULT (extract(epoch from now())::bigint),
    created_at  BIGINT NOT NULL DEFAULT (extract(epoch from now())::bigint)
  );
CREATE INDEX IF NOT EXISTS idx_call_link_guests_link ON call_link_guests(link_id);
